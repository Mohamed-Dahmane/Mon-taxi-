import assert from "node:assert/strict";
import {createSumUpTransport} from "../supabase/functions/taxi-sumup-oauth/sumup-transport.mjs";
const calls=[];let status=200,body;
const scope="transactions.history user.profile_readonly";
const transport=createSumUpTransport({clientId:"fake-client",clientSecret:"fake-secret",fetchImpl:async (url,opts)=>{calls.push({url,opts});return {ok:status===200,status,json:async()=>body};}});
const raw={access_token:"a",refresh_token:"r",token_type:"Bearer",expires_in:3600,scope};
body=raw;
const first=await transport.exchangeCode("test-code");
assert.equal(first.refreshToken,"r");
assert.equal(calls[0].url,"https://api.sumup.com/token");
assert.equal(calls[0].opts.method,"POST");
assert.equal(calls[0].opts.redirect,"error");
const form=new URLSearchParams(calls[0].opts.body);
assert.equal(form.get("grant_type"),"authorization_code");
assert.equal(form.get("redirect_uri"),"https://uenyvsiturkihectolxp.supabase.co/functions/v1/taxi-sumup-oauth");
body={access_token:"b",token_type:"Bearer",expires_in:3600};
const refreshed=await transport.refresh(first);
assert.equal(refreshed.refreshToken,"r");
assert.equal(new URLSearchParams(calls[1].opts.body).get("grant_type"),"refresh_token");
body={...body,refresh_token:"new-r"};
assert.equal((await transport.refresh(refreshed)).refreshToken,"new-r");
body={transaction_data:{transaction_code:"T1",merchant_code:"M1",amount:"65.00",currency:"EUR",status:"SUCCESSFUL",timestamp:"2026-11-25T12:00:00Z"},acquirer_data:{private:"not returned"}};
const args={accessToken:"b",merchant:"M1",reference:"T1",cents:6500};
assert.equal((await transport.getReceipt(args)).amountCents,6500);
assert.equal(calls.at(-1).url,"https://api.sumup.com/v1.1/receipts/T1?mid=M1");
assert.equal(calls.at(-1).opts.method,"GET");
assert.equal(calls.at(-1).opts.headers.Authorization,"Bearer b");
assert.equal((await transport.getReceipt(args)).acquirer_data,undefined);
const before=calls.length;
await assert.rejects(transport.getReceipt({...args,reference:"../payment"}),/request_invalid/);
assert.equal(calls.length,before);
await assert.rejects(transport.getReceipt({...args,merchant:"M2"}),/receipt_mismatch/);
status=400;body={error:"invalid_grant",error_description:"do not echo"};
await assert.rejects(transport.refresh(first),/^Error: reauthorize$/);
status=429;await assert.rejects(transport.getReceipt(args),/sumup_rate_limit/);
status=401;await assert.rejects(transport.getReceipt(args),/sumup_unauthorized/);
status=403;await assert.rejects(transport.getReceipt(args),/sumup_forbidden/);
console.log("SumUp transport: isolated exchange, refresh, receipt read, denial and validation passed");
