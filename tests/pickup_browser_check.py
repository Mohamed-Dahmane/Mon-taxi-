from playwright.sync_api import sync_playwright, expect
import os

with sync_playwright() as p:
    browser=p.chromium.launch(executable_path=os.environ['CHROME_PATH'],args=['--no-sandbox'])
    context=browser.new_context(viewport={'width':420,'height':850},permissions=['clipboard-read','clipboard-write'])
    page=context.new_page()
    errors=[]
    page.on('pageerror',lambda error:(errors.append(str(error)),print("Browser error:",error,flush=True)))
    page.on('dialog',lambda d:(errors.append(d.message),d.dismiss()))
    page.route('**/*',lambda route:route.continue_() if route.request.url.startswith('http://localhost:8765') else route.abort())
    page.add_init_script('''if(location.pathname==="/"){
      localStorage.setItem("taxi-private-session",'{"access_token":"test","expires_at":9999999999}');
      if(!localStorage.getItem("taxi-pickup-prototype-v1")){
        localStorage.setItem("taxi-pickup-prototype-v1",'[{"client":"FICHE DE TEST"}]');
        localStorage.setItem("montaxi:hotel-commissions:courses-v1",'[{"id":"existing","hotel":"Moxy","contact":"Alexis","destination":"Zaventem","date":"2026-11-01","recordedTime":"12:00","bookingMode":"Direct","reservationStatus":"validated","validatedAt":"2026-11-01T12:00","driver":"other","driverName":"Mohaled 70","completedDriver":"other","completedDriverName":"Mohaled 70","amount":10}]');
        localStorage.setItem("montaxi:hotel-commissions:directory-v1", JSON.stringify({contacts:["Mohaled 70","Mohamed 70"], driverOrder:["Mohaled 70","Mohamed 70"]}));
        localStorage.setItem("gestion-taxi-test-v3", JSON.stringify({months:{"2026-9":{days:{"15":{caisse:"123.45"}}}}}));
      }
    }''')
    page.goto('http://localhost:8765/')
    intro=page.get_by_role("button",name="Appuie pour ouvrir")
    try:
        intro.click(timeout=5000)
    except Exception:
        pass
    navigation = page.locator('#taxiPageLocation')
    expect(navigation.get_by_role('button')).to_have_text(['Accueil','Bilan'])
    page.locator('#taxiPageNext').click()
    expect(page.locator('#details')).to_have_class('page active')
    expect(page.get_by_role('heading',name='Journal du mois')).to_be_visible()
    page.get_by_role('button',name='Historique',exact=True).click()
    expect(page.locator('#archiveMonths')).to_contain_text('Octobre 2026')
    page.get_by_text('Recettes par date',exact=True).click()
    expect(page.locator('#archiveDays')).to_contain_text('15.10.2026')
    page.get_by_role('button',name='Sauvegarde',exact=True).click()
    expect(page.get_by_role('button',name='Exporter une sauvegarde')).to_be_visible()
    page.get_by_role('button',name='Mois',exact=True).click()
    page.locator('#taxiPageNext').click()
    expect(page.locator('#home')).to_have_class('page active')
    navigation.get_by_role('button',name='Bilan').click()
    directory = page.evaluate('JSON.parse(localStorage.getItem("montaxi:hotel-commissions:directory-v1"))')
    assert directory['contacts'] == ['Mohamed 70'], directory
    assert directory['driverOrder'] == ['Mohamed 70'], directory
    page.locator('#openHotelCommissions').click()
    hotel=page.frame_locator('#hotelCommissionsFrame')
    hotel.locator('#startReservation').click()
    expect(hotel.locator('#rideDirection')).to_be_visible()
    hotel.locator('#rideDropoff').click()
    expect(hotel.locator('#reservationForm')).to_be_visible()
    expect(hotel.locator('#reservationHotelOptions')).to_be_visible()
    expect(hotel.locator('#rideDirection')).not_to_be_visible()
    hotel.locator('#reservationDate').evaluate("""date => {
      const tomorrow = new Date()
      tomorrow.setDate(tomorrow.getDate() + 1)
      date.value = new Intl.DateTimeFormat('sv-SE', {timeZone: 'Europe/Brussels'}).format(tomorrow)
      date.dispatchEvent(new Event('change'))
    }""")
    hotel.locator('#reservationTypedHour').fill('14')
    hotel.locator('#reservationTypedMinute').fill('30')
    hotel.locator('#nextReservationStep').click()
    hotel.locator('#saveReservation').click()
    expect(page.locator('#hotelCommissionsDialog')).not_to_be_visible()
    expect(page.locator('#home')).to_have_class('page active')
    page.locator('#openHotelPlanning').click()
    expect(hotel.locator('#reservationList')).to_contain_text('14:30')
    expect(hotel.locator('#reservationList')).to_contain_text('Airport BRU')
    page.locator('#closeHotelCommissions').click()
    page.locator('#openHotelCommissions').click()
    hotel.locator('#startReservation').click()
    hotel.locator('#ridePickup').click()
    pickup=page.frame_locator('#hotelPickupFrame')
    expect(pickup.locator('#save')).to_have_text('Enregistrer la course')
    expect(pickup.locator('h1')).to_contain_text('Pick-up')
    assert pickup.locator('#planning').count()==0
    pickup.locator('#dateChoose').click()
    expect(pickup.locator('#calendar')).to_be_visible()
    pickup.locator('#calendar [data-cal=next]').click()
    pickup.locator('#calendar [data-day="15"]').click()
    pickup.locator('#timeMode').select_option('arrival')
    pickup.locator('#arrivalHour').fill('15')
    pickup.locator('#arrivalMinute').fill('30')
    pickup.locator('#hotelSearch').fill('The Standard')
    pickup.locator('#contactSearch').fill('Fal')
    pickup.locator('#contactSearch').press('Tab')
    pickup.locator('#client').fill('client exemple')
    pickup.locator('#phone').fill('+32470123456')
    pickup.locator('#flight').fill('sn1234')
    pickup.locator('#price').fill('0')
    pickup.locator('#vehicle').select_option('Van')
    pickup.locator('#vans').fill('2')
    pickup.locator('#passengers').fill('5')
    pickup.locator('#reminder60').uncheck()
    pickup.locator('#save').click()
    assert not errors,errors
    expect(page.locator('#hotelPickup')).not_to_be_visible()
    expect(page.locator('#hotelCommissionsDialog')).not_to_be_visible()
    expect(page.locator('#home')).to_have_class('page active')
    expect(page.locator('#toast')).to_have_text('Course enregistrée dans le planning')
    page.locator('#openHotelPlanning').click()
    expect(hotel.locator('#reservationList')).to_contain_text('Client Exemple')
    expect(hotel.locator('#reservationList')).to_contain_text('SN1234')
    expect(hotel.locator('#reservationList')).to_contain_text('2 × Van')
    expect(hotel.locator('#reservationList')).to_contain_text('Prix annoncé')
    expect(hotel.locator('#reservationList')).not_to_contain_text('FICHE DE TEST')
    hotel.locator('.reservation-card').filter(has_text='SN1234').get_by_role('button',name='Copier la course').click()
    expect(hotel.locator('#reservationBoardMessage')).to_have_text('Course copiée.')
    assert 'SN1234' in page.evaluate('navigator.clipboard.readText()')
    hotel.get_by_role('button',name='Modifier le pick-up').click()
    expect(pickup.locator('#flight')).to_have_value('SN1234')
    expect(pickup.locator('#arrivalHour')).to_have_value('15')
    expect(pickup.locator('#contactSearch')).to_have_value('Fal')
    pickup.locator('#company').fill('Brussels Airlines')
    pickup.locator('#save').click()
    assert not errors,errors
    expect(hotel.locator('#reservationList')).to_contain_text('Brussels Airlines')
    page.locator('#closeHotelCommissions').click()
    page.reload()
    try:
        intro.click(timeout=5000)
    except Exception:
        pass
    page.locator('#openHotelPlanning').click()
    expect(hotel.locator('#reservationList')).to_contain_text('Brussels Airlines')
    page.locator('#hotelQuickMenuBtn').click()
    page.locator('#hotelQuickMenu [data-quick=hotelAll]').click()
    expect(hotel.locator('#reservationList')).to_contain_text('Moxy')
    expect(hotel.locator('#reservationList')).to_contain_text('Attribuée à · Mohamed 70')
    expect(hotel.locator('#reservationList')).to_contain_text('Effectuée par · Mohamed 70')
    expect(hotel.locator('#reservationList')).not_to_contain_text('Mohaled 70')
    expect(hotel.locator('#reservationList')).to_contain_text('Brussels Airlines')
    page.locator('#hotelQuickMenuBtn').click()
    page.locator('#hotelQuickMenu [data-quick=direct]').click()
    hotel.locator('#ridePickup').click()
    expect(pickup.locator('h1')).to_contain_text('Pick-up')
    pickup.locator('#hotelSearch').fill('The Standard')
    pickup.locator('#contactSearch').fill('Fal')
    pickup.locator('#contactSearch').press('Tab')
    pickup.locator('#client').fill('client direct')
    pickup.locator('#phone').fill('+32470987654')
    pickup.locator('#flight').fill('sn9876')
    pickup.locator('#save').click()
    assert not errors,errors
    expect(hotel.locator('#reservationList')).to_contain_text('Client Direct')
    expect(hotel.locator('#reservationList')).to_contain_text('Course directe · Effectuée')
    courses=page.evaluate('JSON.parse(localStorage.getItem("montaxi:hotel-commissions:courses-v1"))')
    assert len(courses)==4,courses
    future=next(c for c in courses if c.get('scheduledDate') and c.get('pickup'))
    assert future['contact']=='Fal' and future['announcedPrice']==0 and future['pickup']['reminder60'] is False,future
    assert page.evaluate('(c)=>TaxiHotels.reminders([c]).map(r=>r.minutes)',future)==[30]
    assert not errors,errors
    page.locator('#hotelQuickMenuBtn').click()
    page.locator('#hotelQuickMenu [data-quick=hotelArchives]').click()
    expect(hotel.locator('#reservationBoardTitle')).to_have_text('Archives des courses')
    expect(hotel.locator('#reservationStatusFilters [data-reservation-status=all]')).to_have_attribute('aria-pressed', 'true')
    dropoff = next(c for c in courses if c.get('scheduledTime') == '14:30' and not c.get('pickup'))
    dropoff_card = hotel.locator(f'.reservation-card[data-entry-id="{dropoff["id"]}"]')
    pickup_card = hotel.locator(f'.reservation-card[data-entry-id="{future["id"]}"]')
    expect(dropoff_card).to_contain_text('Réservation à venir')
    expect(dropoff_card).to_contain_text('Attribuée à · Moi')
    expect(pickup_card).to_contain_text('Client Exemple')
    page.clock.set_fixed_time(dropoff['scheduledDate'] + 'T14:40:00+01:00')
    hotel.locator('#reservationStatusFilters [data-reservation-status=validated]').click()
    hotel.locator('#reservationStatusFilters [data-reservation-status=all]').click()
    expect(dropoff_card.locator('.reservation-validate')).to_be_enabled()
    dropoff_card.locator('.reservation-validate').click()
    expect(hotel.locator('#planningDriverTitle')).to_have_text('Confirmer la course effectuée')
    hotel.locator('#planningDriver [data-driver-option=other]').click()
    hotel.locator('#planningDriverList [data-driver=Alexis]').click()
    hotel.get_by_role('button', name='Valider la course').click()
    hotel.locator('#reservationStatusFilters [data-reservation-status=validated]').click()
    expect(dropoff_card).to_contain_text('Attribuée à · Moi')
    expect(dropoff_card).to_contain_text('Effectuée par · Alexis')
    updated = page.evaluate('JSON.parse(localStorage.getItem("montaxi:hotel-commissions:courses-v1"))')
    saved = next(c for c in updated if c['id'] == dropoff['id'])
    assert saved['driver'] == 'self' and saved['completedDriverName'] == 'Alexis'
    assert not errors, errors
    print('Chromium mobile · Dépose et Pick-up, retour accueil, planning, toutes les archives et chauffeurs vérifiés.')
